#!/usr/bin/env bash

# ───────────────────────────────────────────────────────────────────────────────
# STARSHIP DOCKER MODULE
# ───────────────────────────────────────────────────────────────────────────────
# Показує:
#   󰡨 default ↑ 4
# або:
#   󰡨 default ↑ 3 ⟳ 1
# Де:
#   󰡨       — Docker
#   default — активний Docker context
#   ↑ 3     — 3 запущені контейнери
#   ⟳ 1     — 1 зупинений контейнер
# Модуль запускається тільки в Docker/Compose проєкті.

set -Eeuo pipefail

# ───────────────────────────────────────────────────────────────────────────────
# Docker перевірка
# ───────────────────────────────────────────────────────────────────────────────
if ! command -v docker >/dev/null 2>&1; then
    exit 0
fi

# ───────────────────────────────────────────────────────────────────────────────
# Визначення Docker-проєкту
# ───────────────────────────────────────────────────────────────────────────────
is_docker_project() {
    [[ -f "Dockerfile" ]] ||
    [[ -f "docker-compose.yml" ]] ||
    [[ -f "docker-compose.yaml" ]] ||
    [[ -f "compose.yml" ]] ||
    [[ -f "compose.yaml" ]]
}

if ! is_docker_project; then
    exit 0
fi

# ───────────────────────────────────────────────────────────────────────────────
# Docker daemon
# ───────────────────────────────────────────────────────────────────────────────
if ! docker info >/dev/null 2>&1; then
    exit 0
fi

# ───────────────────────────────────────────────────────────────────────────────
# Docker context
# ───────────────────────────────────────────────────────────────────────────────
context="$(docker context show 2>/dev/null || true)"

if [[ -z "$context" ]]; then
    context="unknown"
fi

# ───────────────────────────────────────────────────────────────────────────────
# Кількість запущених контейнерів
# ───────────────────────────────────────────────────────────────────────────────
running="$(docker ps -q 2>/dev/null | wc -l)"
running="${running//[[:space:]]/}"

# ───────────────────────────────────────────────────────────────────────────────
# Кількість зупинених контейнерів
# ───────────────────────────────────────────────────────────────────────────────
stopped="$(docker ps -aq 2>/dev/null | wc -l)"
stopped="${stopped//[[:space:]]/}"
stopped=$((stopped - running))

if (( stopped < 0 )); then
    stopped=0
fi

# ───────────────────────────────────────────────────────────────────────────────
# Вивід
# ───────────────────────────────────────────────────────────────────────────────
output="󰡨 ${context}"

if (( running > 0 )); then
    output+=" ↑ ${running}"
fi

if (( stopped > 0 )); then
    output+=" ⟳ ${stopped}"
fi

echo "$output"
